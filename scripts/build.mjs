import { build } from 'esbuild'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toJsonSchema } from '@valibot/to-json-schema'
import { projectSchema } from '../config/project.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const schema = {
  ...toJsonSchema(projectSchema, { target: 'draft-07', typeMode: 'input', errorMode: 'throw' }),
  title: 'Xova project workflow configuration',
  $comment: 'Generated by pnpm build; edit config/project.mjs.',
}
const sources = [
  ['semver', "export { parse, validRange } from 'semver'"],
  ['project-config', "export { parseProjectConfig } from './config/project.mjs'"],
]
const results = await Promise.all(sources.map(([name, contents]) => build({
  absWorkingDir: root,
  stdin: { contents, resolveDir: root },
  bundle: true, platform: 'node', format: 'esm', target: 'node22',
  outfile: join(root, 'dist', name + '.mjs'), write: false, legalComments: 'eof',
  banner: { js: '// Generated by pnpm build; edit scripts/build.mjs, the schema or the locked dependency.' },
})))
const files = [
  ...results.flatMap(({ outputFiles }) => outputFiles.map(file => [file.path, file.contents])),
  [join(root, 'config/project.schema.json'), JSON.stringify(schema, null, 2) + '\n'],
  [join(root, 'dist/semver.LICENSE'), readFileSync(join(root, 'node_modules/semver/LICENSE'))],
  [join(root, 'dist/valibot.LICENSE'), readFileSync(join(root, 'node_modules/valibot/LICENSE.md'))],
]
for (const [path, bytes] of files) {
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || !readFileSync(path).equals(Buffer.from(bytes)))
      throw new Error('Generated distribution is stale. Run pnpm build.')
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, bytes)
  }
}
