import { build } from 'esbuild'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const { outputFiles } = await build({
  absWorkingDir: root,
  stdin: { contents: "export { parse, validRange } from 'semver'", resolveDir: root },
  bundle: true, platform: 'node', format: 'esm', target: 'node22',
  outfile: join(root, 'dist/semver.mjs'), write: false, legalComments: 'eof',
  banner: { js: '// Generated by pnpm build; edit scripts/build.mjs or upgrade the locked dependency.' },
})
const files = [
  ...outputFiles.map(file => [file.path, file.contents]),
  [join(root, 'dist/semver.LICENSE'), readFileSync(join(root, 'node_modules/semver/LICENSE'))],
]
for (const [path, bytes] of files) {
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || !readFileSync(path).equals(Buffer.from(bytes)))
      throw new Error('Bundled semver is stale. Run pnpm build.')
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, bytes)
  }
}
